export function lookupVendorByMac(mac: string): string | null {
  const normalized = mac.toUpperCase().replace(/-/g, ":");
  const prefix = normalized.split(":").slice(0, 3).join(":");
  return OUI_VENDORS[prefix] ?? null;
}
